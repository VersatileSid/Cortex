"""On-demand, presentation-only PDF reports for persisted inspections."""
from __future__ import annotations

from datetime import datetime, timezone
from io import BytesIO
from pathlib import Path
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import cm
from reportlab.platypus import Image, PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle
from sqlalchemy import select
from sqlalchemy.orm import Session

from backend.app.models import ComplianceResult, ComplianceRule, ExtractedField, Inspection, InspectionImage, Manufacturer, OcrResult, Product, User


class InspectionReportService:
    def __init__(self, db: Session, upload_dir: Path):
        self.db, self.upload_dir = db, upload_dir.resolve()

    @staticmethod
    def _text(value: object | None) -> str:
        return escape(str(value)) if value not in (None, "") else "Not available"

    @staticmethod
    def _footer(canvas, document) -> None:
        canvas.saveState()
        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(colors.HexColor("#526176"))
        canvas.drawString(document.leftMargin, 1.1 * cm, f"Generated by LabelGuard · {document.inspection_number}")
        canvas.drawRightString(A4[0] - document.rightMargin, 1.1 * cm, f"Page {document.page}")
        canvas.restoreState()

    def _heading(self, title: str, styles) -> list:
        return [Spacer(1, 0.25 * cm), Paragraph(title, styles["section"]), Spacer(1, 0.12 * cm)]

    def _table(self, rows: list[tuple[str, object | None]], styles) -> Table:
        table = Table([[Paragraph(f"<b>{self._text(label)}</b>", styles["body"]), Paragraph(self._text(value), styles["body"])] for label, value in rows], colWidths=[4.5 * cm, 12.5 * cm], repeatRows=0)
        table.setStyle(TableStyle([("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#F4F7FB")), ("GRID", (0, 0), (-1, -1), 0.35, colors.HexColor("#DDE4ED")), ("VALIGN", (0, 0), (-1, -1), "TOP"), ("LEFTPADDING", (0, 0), (-1, -1), 7), ("RIGHTPADDING", (0, 0), (-1, -1), 7), ("TOPPADDING", (0, 0), (-1, -1), 6), ("BOTTOMPADDING", (0, 0), (-1, -1), 6)]))
        return table

    def generate(self, inspection: Inspection) -> bytes:
        """Render only persisted data. Missing optional workflow layers are normal."""
        product = self.db.get(Product, inspection.product_id) if inspection.product_id else None
        manufacturer = self.db.get(Manufacturer, inspection.manufacturer_id) if inspection.manufacturer_id else None
        inspector = self.db.get(User, inspection.user_id) if inspection.user_id else None
        image = self.db.scalar(select(InspectionImage).where(InspectionImage.inspection_id == inspection.id).order_by(InspectionImage.created_at.desc()))
        ocr = self.db.scalar(select(OcrResult).where(OcrResult.inspection_id == inspection.id).order_by(OcrResult.created_at.desc()))
        fields = self.db.scalars(select(ExtractedField).where(ExtractedField.inspection_id == inspection.id).order_by(ExtractedField.field_name)).all()
        findings = self.db.scalars(select(ComplianceResult).where(ComplianceResult.inspection_id == inspection.id).join(ComplianceRule).order_by(ComplianceRule.rule_code)).all()

        output = BytesIO()
        document = SimpleDocTemplate(output, pagesize=A4, rightMargin=1.7 * cm, leftMargin=1.7 * cm, topMargin=1.7 * cm, bottomMargin=1.8 * cm, title=f"LabelGuard inspection {inspection.inspection_number}")
        document.inspection_number = inspection.inspection_number
        styles = getSampleStyleSheet()
        styles.add(ParagraphStyle(name="titleLG", parent=styles["Title"], alignment=TA_CENTER, textColor=colors.HexColor("#087F70"), fontSize=20, leading=25))
        styles.add(ParagraphStyle(name="section", parent=styles["Heading2"], textColor=colors.HexColor("#087F70"), fontSize=13, leading=17, spaceBefore=7))
        styles.add(ParagraphStyle(name="body", parent=styles["BodyText"], fontSize=9, leading=12, wordWrap="CJK"))
        story = [Paragraph("LABELGUARD", styles["titleLG"]), Paragraph("Food Label Inspection Report", styles["Heading2"]), Spacer(1, 0.35 * cm)]
        story += self._heading("Inspection Information", styles)
        story.append(self._table([("Inspection ID", inspection.inspection_number), ("Inspector", inspector.username if inspector else None), ("Inspection date", inspection.created_at), ("Inspection status", inspection.status), ("Report generated at", datetime.now(timezone.utc).isoformat())], styles))
        story += self._heading("Product Information", styles)
        field_values = {field.field_name: field.value for field in fields}
        story.append(self._table([("Product name", field_values.get("product_name") or (product.name if product else None)), ("Manufacturer", field_values.get("manufacturer") or (manufacturer.name if manufacturer else None)), ("Batch / lot number", field_values.get("batch_number") or field_values.get("lot_number")), ("Expiry date", field_values.get("expiry_date") or field_values.get("best_before")), ("Net quantity", field_values.get("net_quantity")), ("MRP", field_values.get("mrp"))], styles))
        if image:
            image_path = (self.upload_dir / image.storage_key).resolve()
            if image_path.is_relative_to(self.upload_dir) and image_path.is_file():
                story += self._heading("Original Label Image", styles)
                picture = Image(str(image_path)); picture._restrictSize(16 * cm, 10 * cm); story.append(picture)
        story += self._heading("OCR Results", styles)
        languages = ", ".join(ocr.languages) if ocr and ocr.languages else "Not available"
        story.append(Paragraph(f"<b>Detected OCR languages:</b> {self._text(languages)}", styles["body"]))
        story.append(Spacer(1, 0.1 * cm)); story.append(Paragraph(self._text(ocr.raw_text if ocr else "No text detected."), styles["body"]))
        story += self._heading("Extracted Information", styles)
        story.append(self._table([(field.field_name.replace("_", " ").title(), field.value) for field in fields] or [("Information", "Not available")], styles))
        story += self._heading("Compliance Result", styles)
        counts = {state: sum(result.result == state for result in findings) for state in ("PASS", "REVIEW", "FAIL")}
        overall = "FAIL" if counts["FAIL"] else "REVIEW" if counts["REVIEW"] else "PASS" if findings else "Not available"
        story.append(self._table([("Overall status", overall), ("Rules passed", counts["PASS"]), ("Warnings", counts["REVIEW"]), ("Violations", counts["FAIL"])], styles))
        if findings:
            story.append(Spacer(1, 0.18 * cm))
            finding_rows = [[Paragraph("<b>Rule</b>", styles["body"]), Paragraph("<b>Status</b>", styles["body"]), Paragraph("<b>Severity / message</b>", styles["body"])]]
            for result in findings:
                finding_rows.append([Paragraph(self._text(result.rule.description.split(".", 1)[0]), styles["body"]), Paragraph(self._text(result.result), styles["body"]), Paragraph(self._text(f"{result.rule.severity}: {result.explanation}"), styles["body"])])
            finding_table = Table(finding_rows, colWidths=[5 * cm, 2.5 * cm, 9.5 * cm], repeatRows=1)
            finding_table.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EAF8F5")), ("GRID", (0, 0), (-1, -1), 0.35, colors.HexColor("#DDE4ED")), ("VALIGN", (0, 0), (-1, -1), "TOP"), ("PADDING", (0, 0), (-1, -1), 6)])); story.append(finding_table)
            story += self._heading("Legal Metrology Compliance", styles)
            legal_rows = [[Paragraph("<b>Rule / status</b>", styles["body"]), Paragraph("<b>Finding / extracted value / evidence</b>", styles["body"])] ]
            for result in findings:
                legal_rows.append([Paragraph(self._text(f"{result.rule.rule_code} — {result.rule.description.split('.', 1)[0]} — {result.result}"), styles["body"]), Paragraph(self._text(f"Finding: {result.explanation}\nExtracted: {result.value or 'Not available'}\nExpected: {result.rule.description}\nEvidence: {result.evidence or 'Not available'}"), styles["body"])])
            legal_table = Table(legal_rows, colWidths=[6 * cm, 11 * cm], repeatRows=1)
            legal_table.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EAF8F5")), ("GRID", (0, 0), (-1, -1), 0.35, colors.HexColor("#DDE4ED")), ("VALIGN", (0, 0), (-1, -1), "TOP"), ("PADDING", (0, 0), (-1, -1), 6)])); story.append(legal_table)
        story += self._heading("Inspection Summary", styles)
        story.append(Paragraph(self._text(f"Overall compliance: {overall}. {counts['PASS']} rules passed, {counts['REVIEW']} warnings, {counts['FAIL']} violations."), styles["body"]))
        document.build(story, onFirstPage=self._footer, onLaterPages=self._footer)
        return output.getvalue()
